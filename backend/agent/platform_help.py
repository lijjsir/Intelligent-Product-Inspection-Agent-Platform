"""Product facts for ordinary-user help, kept alongside the app's user workflow."""

import re

PLATFORM_HELP_PATTERNS = [
    re.compile(pattern, re.I)
    for pattern in (
        r"(系统|平台|PIAP).{0,24}(功能|支持|怎么用|如何使用|能做|可以做|能问|可以问|操作|入口|权限)",
        r"(怎么|如何|怎样|在哪|哪里).{0,12}(创建|新建|提交|发起|查看|查询|下载|导出|上传|设置|使用).{0,12}(任务|报告|结果|图片|文件|质检|质监|对话)",
        r"(任务|报告|个人设置|AI.{0,1}对话|会议室).{0,12}(怎么用|如何使用|在哪|哪里|流程|步骤|入口|权限)",
        r"(你|助手).{0,8}(能做什么|会做什么|可以做什么|能帮|能问|可以问)",
    )
]


def is_platform_help_query(query: str) -> bool:
    return is_inspection_preparation_query(query) or any(pattern.search(query) for pattern in PLATFORM_HELP_PATTERNS)


def is_inspection_preparation_query(query: str) -> bool:
    return bool(re.search(
        r"(检测|质检|检验)(之前|前).{0,40}(准备|提供|需要|图片|资料|材料|要求|视角)"
        r"|(检测|质检|检验).{0,8}(要|需要|应该).{0,8}(准备|提供|拍摄)"
        r"|(如何|怎样|需要|应该).{0,12}(准备|提供|拍摄).{0,20}(检测|质检|检验|图片|资料|材料)",
        str(query or ""), re.I,
    ))


